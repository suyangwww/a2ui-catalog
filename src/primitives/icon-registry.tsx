const SIZE_PX: Readonly<Record<string, number>> = {
  xs: 14,
  sm: 16,
  md: 20,
  lg: 24,
  xl: 32,
};

export function LuminaIconGlyph({
  name,
  size = 'md',
  className,
}: {
  name: unknown;
  size?: 'xs' | 'sm' | 'md' | 'lg' | 'xl' | number | undefined;
  className?: string | undefined;
}) {
  const px = typeof size === 'number' ? size : (SIZE_PX[size] ?? 20);

  if (isPlainRecord(name) && 'svgPath' in name) {
    const d = readString(name.svgPath);
    return (
      <svg
        width={px}
        height={px}
        viewBox="0 0 24 24"
        fill="currentColor"
        className={className}
        aria-hidden="true"
      >
        <path d={d} />
      </svg>
    );
  }

  const key = typeof name === 'string' ? name : '';
  const Comp = ICON_MAP[key] ?? Sparkles;
  return <Comp size={px} strokeWidth={1.75} className={className} aria-hidden="true" />;
}
