import { LUMINA_V1_CATALOG_ID } from '@a2ui-catalog/core';

export interface PropertyDoc {
  name: string;
  required?: boolean;
  typeLabel: string;
  description: string;
}

export interface ComponentReferenceEntry {
  index: number;
  name: string;
  group: string;
  summary: string;
  whenToUse: string;
  platformNote: string;
  properties: PropertyDoc[];
  messages: Record<string, unknown>[];
}

function surface(
  id: string,
  components: Array<Record<string, unknown>>,
  dataModel?: Record<string, unknown>,
): Record<string, unknown>[] {
  return [
    {
      version: '1.0',
      createSurface: {
        surfaceId: id,
        catalogId: LUMINA_V1_CATALOG_ID,
        ...(dataModel ? { dataModel } : {}),
        components,
      },
    },
  ];
}

