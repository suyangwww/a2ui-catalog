import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const pkgRoot = path.resolve(__dirname, '..');
const srcDir = path.join(pkgRoot, 'src');
const distDir = path.join(pkgRoot, 'dist');
const platformsDir = path.join(distDir, 'platforms');

fs.mkdirSync(platformsDir, { recursive: true });

const colors = JSON.parse(fs.readFileSync(path.join(srcDir, 'colors.tokens.json'), 'utf8'));
const typography = JSON.parse(fs.readFileSync(path.join(srcDir, 'typography.tokens.json'), 'utf8'));
const layout = JSON.parse(fs.readFileSync(path.join(srcDir, 'layout.tokens.json'), 'utf8'));
const motion = JSON.parse(fs.readFileSync(path.join(srcDir, 'motion.tokens.json'), 'utf8'));

function toCssVars(record, prefix = '--lumina-') {
  return Object.entries(record)
    .map(([key, value]) => `  ${prefix}${key}: ${value};`)
    .join('\n');
}

const cssContent = `/* Generated by @a2ui-catalog/tokens — Do not edit directly */
:root,
[data-lumina-theme="light"] {
${toCssVars(colors.light)}
  --lumina-font-sans: ${typography.fonts.sans};
  --lumina-font-display: ${typography.fonts.display};
  --lumina-font-mono: ${typography.fonts.mono};
${toCssVars(layout.radii, '--lumina-radius-')}
${toCssVars(layout.spacing, '--lumina-space-')}
  --lumina-glass-blur: ${layout.glass.blur};
  --lumina-glass-saturate: ${layout.glass.saturate};
  --lumina-touch-target: ${layout.touch.minTargetFine};
  color-scheme: light;
}

@media (prefers-color-scheme: dark) {
  :root:not([data-lumina-theme="light"]) {
${toCssVars(colors.dark)}
    color-scheme: dark;
  }
}

[data-lumina-theme="dark"] {
${toCssVars(colors.dark)}
  color-scheme: dark;
}

@media (pointer: coarse) {
  :root,
  [data-lumina-theme] {
    --lumina-touch-target: ${layout.touch.minTargetCoarse};
  }
}
`;

fs.writeFileSync(path.join(distDir, 'lumina-tokens.css'), cssContent, 'utf8');

